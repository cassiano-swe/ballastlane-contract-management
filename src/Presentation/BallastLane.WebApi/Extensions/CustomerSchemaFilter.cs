using BallastLane.WebApi.Models.Requests.Customers;
using BallastLane.WebApi.Models.Responses.Customers;
using Microsoft.OpenApi.Models;
using Microsoft.OpenApi.Any;
using BallastLane.Domain.Enums;
using Swashbuckle.AspNetCore.SwaggerGen;
namespace BallastLane.WebApi.Extensions;
public sealed class CustomerSchemaFilter : ISchemaFilter
{
    internal const string ExampleVersion = "c53db246-a877-43e1-952d-90fdedfb6781";
    private const string ExampleNewVersion = "a7280e43-7c4d-4d18-a09e-8c3a214e6732";

    public void Apply(OpenApiSchema schema, SchemaFilterContext context)
    {
        if (context.Type == typeof(CustomerType)) { schema.Description = "Allowed values: Individual or Company. Numeric values are not accepted."; schema.Type = "string"; schema.Format = null; schema.Enum = new List<IOpenApiAny> { new OpenApiString("Individual"), new OpenApiString("Company") }; return; }
        if (context.Type == typeof(CreateCustomerResponse)
            || context.Type == typeof(ListCustomersResponse)
            || context.Type == typeof(GetCustomerByIdResponse))
        {
            schema.Properties["version"].Description = "The optimistic concurrency token representing the current persisted state of the customer. Use this token when updating or deactivating the customer.";
            schema.Properties["version"].Example = new OpenApiString(ExampleVersion);
        }

        if (context.Type == typeof(ListCustomersResponse) || context.Type == typeof(GetCustomerByIdResponse))
            schema.Properties["active"].Description = "Whether the customer is currently active.";

        if (context.Type == typeof(UpdateCustomerResponse))
        {
            schema.Properties["version"].Description = "The new concurrency token generated by the successful update. This token must be used in subsequent modification requests.";
            schema.Properties["version"].Example = new OpenApiString(ExampleNewVersion);
        }

        if (context.Type == typeof(UpdateCustomerRequest))
        {
            schema.Properties["version"].Nullable = false;
            schema.Properties["version"].Description = "The concurrency token obtained from a previous customer response. The update succeeds only if this token matches the currently persisted customer version.";
            schema.Properties["version"].Example = new OpenApiString(ExampleVersion);
            schema.Properties["tradeName"].Nullable = true;
            schema.Properties["tradeName"].Description = "Only allowed for companies. Omit it or send null to clear the stored value.";
        }

        if (context.Type != typeof(CreateCustomerRequest) && context.Type != typeof(UpdateCustomerRequest)) return;
        schema.Properties["name"].MaxLength = 200;
        schema.Properties["tradeName"].MaxLength = 200;
        schema.Properties["taxId"].MaxLength = 50;
        schema.Properties["email"].MaxLength = 254;
    }
}
